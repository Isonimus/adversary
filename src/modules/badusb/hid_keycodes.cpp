// ---------------------------------------------------------------------------
// Key name → HID usage (physical key position, layout-independent)
// ---------------------------------------------------------------------------
struct KeyNameDef { const char* name; uint8_t usage; };
static const KeyNameDef KEY_NAMES[] = {
    {"ENTER",       0x28}, {"RETURN",   0x28},
    {"ESC",         0x29}, {"ESCAPE",   0x29},
    {"BACKSPACE",   0x2A},
    {"TAB",         0x2B},
    {"SPACE",       0x2C},
    {"F1",  0x3A}, {"F2",  0x3B}, {"F3",  0x3C}, {"F4",  0x3D},
    {"F5",  0x3E}, {"F6",  0x3F}, {"F7",  0x40}, {"F8",  0x41},
    {"F9",  0x42}, {"F10", 0x43}, {"F11", 0x44}, {"F12", 0x45},
    {"PRINTSCREEN", 0x46},
    {"CAPSLOCK",    0x39},
    {"INSERT",      0x49},
    {"HOME",        0x4A},
    {"PAGEUP",      0x4B},
    {"DELETE",      0x4C},
    {"END",         0x4D},
    {"PAGEDOWN",    0x4E},
    {"RIGHT",       0x4F},
    {"LEFT",        0x50},
    {"DOWN",        0x51},
    {"UP",          0x52},
    {nullptr, 0}
};

uint8_t keyNameToUsage(const char* name) {
    if (!name || !*name) return 0;
    // Single char: a-z / A-Z → usage 0x04+(pos), 0-9 special
    if (name[1] == '\0') {
        char c = name[0];
        if (c >= 'a' && c <= 'z') return 0x04 + (c - 'a');
        if (c >= 'A' && c <= 'Z') return 0x04 + (c - 'A');
        if (c == '0') return 0x27;
        if (c >= '1' && c <= '9') return 0x1E + (c - '1');
    }
    for (const KeyNameDef* d = KEY_NAMES; d->name; ++d) {
        if (strcasecmp(d->name, name) == 0) return d->usage;
    }
    return 0;
}

// ---------------------------------------------------------------------------
// Modifier name → bit mask
// ---------------------------------------------------------------------------
struct ModNameDef { const char* name; uint8_t bit; };
static const ModNameDef MOD_NAMES[] = {
    {"CTRL",    MOD_LCTRL},  {"CONTROL", MOD_LCTRL},
    {"SHIFT",   MOD_LSHIFT},
    {"ALT",     MOD_LALT},
    {"GUI",     MOD_LGUI},   {"WINDOWS", MOD_LGUI}, {"COMMAND", MOD_LGUI},
    {nullptr, 0}
};

uint8_t modNameToBit(const char* name) {
    for (const ModNameDef* d = MOD_NAMES; d->name; ++d) {
        if (strcasecmp(d->name, name) == 0) return d->bit;
    }
    return 0;
}

